"""Manage a systemd *user* timer that runs `jobpoller run` daily.

Rendering is pure (testable); every systemctl call goes through an injectable runner.
"""

from __future__ import annotations

import os
import re
import shlex
import shutil
import subprocess
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

UNIT = "jobpoller"
FAILED_SUFFIX = "-failed"  # jobpoller-failed.service: curl alert, used by OnFailure=
LAUNCHER_SUFFIX = "-run.sh"  # jobpoller-run.sh: picks a working Python
Runner = Callable[[list[str]], "subprocess.CompletedProcess[str]"]


class ScheduleError(Exception):
    pass


def normalize_time(value: object) -> str:
    """'8:05' -> '08:05'. Also accepts the int YAML produces for an unquoted 8:05 (minutes)."""
    if isinstance(value, bool):
        raise ScheduleError(f"invalid time {value!r}; use HH:MM, e.g. 08:00")
    if isinstance(value, int):  # YAML 1.1 reads unquoted 8:05 as sexagesimal 485
        hours, minutes = divmod(value, 60)
    else:
        match = re.fullmatch(r"\s*(\d{1,2}):(\d{2})\s*", str(value))
        if match is None:
            raise ScheduleError(f"invalid time {value!r}; use HH:MM, e.g. 08:00")
        hours, minutes = int(match.group(1)), int(match.group(2))
    if not (0 <= hours < 24 and 0 <= minutes < 60):
        raise ScheduleError(f"invalid time {value!r}; use HH:MM, e.g. 08:00")
    return f"{hours:02d}:{minutes:02d}"


def _exec_arg(arg: str) -> str:
    """Quote for ExecStart=: handles spaces, and the % and $ that systemd would expand."""
    escaped = arg.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$")
    return f'"{escaped}"'


def python_candidates(primary: Path, config: Path) -> list[str]:
    """Interpreters the launcher tries in order: the one that ran `schedule install`, the
    project's own venv, then whatever `python3` the service's PATH offers."""
    ordered = [str(primary), str(config.parent / ".venv" / "bin" / "python"), "python3"]
    return list(dict.fromkeys(ordered))


def render_launcher(candidates: list[str], config: Path) -> str:
    """POSIX sh that runs `jobpoller run` with the first Python that can import jobpoller.

    A venv whose base interpreter was upgraded or removed still exists on disk but cannot import
    anything; trying the next candidate beats failing every night. If none works it exits 127,
    which fires OnFailure= (see render_failure_service).
    """
    tried = " ".join(shlex.quote(c) for c in candidates)
    return (
        "#!/bin/sh\n"
        "# Generated by `jobpoller schedule install`; re-run that instead of editing.\n"
        f"config={shlex.quote(str(config))}\n"
        f"for py in {tried}; do\n"
        '  command -v "$py" >/dev/null 2>&1 || continue\n'
        "  if ! \"$py\" -c 'import jobpoller.cli' >/dev/null 2>&1; then\n"
        '    echo "jobpoller: skipping $py (cannot import jobpoller)" >&2\n'
        "    continue\n"
        "  fi\n"
        '  exec "$py" -m jobpoller run --config "$config"\n'
        "done\n"
        f'echo "jobpoller: no working Python found; tried: {tried}" >&2\n'
        "exit 127\n"
    )


def render_service(launcher: Path, workdir: Path, on_failure: str | None = None) -> str:
    failure = f"OnFailure={on_failure}\n" if on_failure else ""
    return (
        "[Unit]\n"
        "Description=jobpoller: fetch job boards and queue new matches\n"
        f"{failure}"
        "\n"
        "[Service]\n"
        "Type=oneshot\n"
        f"WorkingDirectory={str(workdir).replace('%', '%%')}\n"
        f"ExecStart=/bin/sh {_exec_arg(str(launcher))}\n"
        "TimeoutStartSec=30min\n"
    )


def render_failure_service(curl: Path, topic: str, unit: str = UNIT) -> str:
    """Push a failure notice with the system curl. Deliberately no Python: this runs when the
    run failed, possibly because Python itself is broken."""
    body = f"The scheduled run failed. Logs: journalctl --user -u {unit}.service -n 30"
    args = [
        str(curl), "--silent", "--show-error", "--fail", "--max-time", "20",
        "-H", "Title: jobpoller run failed", "-H", "Priority: high", "-H", "Tags: warning",
        "-d", body, topic,
    ]  # fmt: skip
    return (
        "[Unit]\n"
        "Description=jobpoller: push a failure notice to ntfy\n"
        "\n"
        "[Service]\n"
        "Type=oneshot\n"
        f"ExecStart={' '.join(_exec_arg(a) for a in args)}\n"
    )


def render_timer(time: str) -> str:
    return (
        "[Unit]\n"
        "Description=Run jobpoller daily\n"
        "\n"
        "[Timer]\n"
        f"OnCalendar=*-*-* {normalize_time(time)}:00\n"
        "Persistent=true\n"
        "\n"
        "[Install]\n"
        "WantedBy=timers.target\n"
    )


def default_unit_dir() -> Path:
    base = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    return base / "systemd" / "user"


def run_systemctl(cmd: list[str]) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=30, check=False)
    except FileNotFoundError as exc:
        raise ScheduleError(f"{cmd[0]} not found; a systemd user session is required") from exc
    except subprocess.TimeoutExpired as exc:
        raise ScheduleError(f"{' '.join(cmd)} timed out") from exc


@dataclass(frozen=True)
class Plan:
    service_path: Path
    timer_path: Path
    service_text: str
    timer_text: str
    commands: tuple[tuple[str, ...], ...]
    launcher_path: Path
    launcher_text: str
    failure_path: Path | None = None  # only when notify.ntfy is set
    failure_text: str = ""

    def describe(self) -> list[str]:
        lines = [f"write {self.service_path}", f"write {self.timer_path}"]
        lines.append(f"write {self.launcher_path}")
        if self.failure_path is not None:
            lines.append(f"write {self.failure_path}")
        lines += [" ".join(c) for c in self.commands]
        return lines


def plan_install(
    python: Path,
    config: Path,
    time: str,
    unit_dir: Path | None = None,
    name: str = UNIT,
    failure_ntfy: str = "",
    curl: Path | None = None,
) -> Plan:
    unit_dir = unit_dir or default_unit_dir()
    launcher = unit_dir / f"{name}{LAUNCHER_SUFFIX}"
    failure_path: Path | None = None
    failure_text = ""
    if failure_ntfy:
        found = curl or (Path(p) if (p := shutil.which("curl")) else None)
        if found is None:
            raise ScheduleError("curl not found; it sends the failure alert (notify.ntfy is set)")
        failure_path = unit_dir / f"{name}{FAILED_SUFFIX}.service"
        failure_text = render_failure_service(found, failure_ntfy, name)
    return Plan(
        service_path=unit_dir / f"{name}.service",
        timer_path=unit_dir / f"{name}.timer",
        service_text=render_service(
            launcher, config.parent, f"{name}{FAILED_SUFFIX}.service" if failure_path else None
        ),
        timer_text=render_timer(time),
        commands=(
            ("systemctl", "--user", "daemon-reload"),
            ("systemctl", "--user", "enable", "--now", f"{name}.timer"),
        ),
        launcher_path=launcher,
        launcher_text=render_launcher(python_candidates(python, config), config),
        failure_path=failure_path,
        failure_text=failure_text,
    )


def _must(runner: Runner, cmd: list[str]) -> None:
    done = runner(cmd)
    if done.returncode != 0:
        raise ScheduleError(f"`{' '.join(cmd)}` failed: {(done.stderr or done.stdout).strip()}")


def apply_install(plan: Plan, runner: Runner = run_systemctl) -> None:
    plan.service_path.parent.mkdir(parents=True, exist_ok=True)
    plan.service_path.write_text(plan.service_text, encoding="utf-8")
    plan.timer_path.write_text(plan.timer_text, encoding="utf-8")
    plan.launcher_path.write_text(plan.launcher_text, encoding="utf-8")
    plan.launcher_path.chmod(0o755)
    if plan.failure_path is not None:
        plan.failure_path.write_text(plan.failure_text, encoding="utf-8")
    for cmd in plan.commands:
        _must(runner, list(cmd))


def remove(unit_dir: Path | None = None, runner: Runner = run_systemctl, name: str = UNIT) -> bool:
    """Disable the timer and delete the unit files; False if nothing was installed."""
    unit_dir = unit_dir or default_unit_dir()
    paths = [
        unit_dir / f"{name}.timer",
        unit_dir / f"{name}.service",
        unit_dir / f"{name}{FAILED_SUFFIX}.service",
        unit_dir / f"{name}{LAUNCHER_SUFFIX}",
    ]
    present = [p for p in paths if p.exists()]
    if not present:
        return False
    runner(["systemctl", "--user", "disable", "--now", f"{name}.timer"])  # ok if already gone
    for path in present:
        path.unlink()
    _must(runner, ["systemctl", "--user", "daemon-reload"])
    return True


@dataclass(frozen=True)
class Status:
    installed: bool
    enabled: bool
    active: bool
    next_run: str
    last_result: str  # e.g. "success", "exit-code", or "never run"
    linger: bool | None  # None if unknown


def _show(runner: Runner, unit: str, props: list[str]) -> dict[str, str]:
    done = runner(["systemctl", "--user", "show", unit, f"--property={','.join(props)}"])
    pairs = (line.partition("=") for line in done.stdout.splitlines() if "=" in line)
    return {k: v for k, _, v in pairs}


def status(runner: Runner = run_systemctl, name: str = UNIT) -> Status:
    timer = _show(
        runner,
        f"{name}.timer",
        ["LoadState", "UnitFileState", "ActiveState", "NextElapseUSecRealtime"],
    )
    installed = timer.get("LoadState", "not-found") != "not-found"
    service = (
        _show(runner, f"{name}.service", ["Result", "ExecMainExitTimestamp"]) if installed else {}
    )
    ran = bool(service.get("ExecMainExitTimestamp"))
    return Status(
        installed=installed,
        enabled=timer.get("UnitFileState") == "enabled",
        active=timer.get("ActiveState") == "active",
        next_run=timer.get("NextElapseUSecRealtime") or "-",
        last_result=(service.get("Result") or "unknown") if ran else "never run",
        linger=_linger(runner),
    )


def _linger(runner: Runner) -> bool | None:
    try:
        done = runner(["loginctl", "show-user", str(os.getuid()), "--property=Linger"])
    except ScheduleError:
        return None
    if done.returncode != 0:
        return None
    return done.stdout.strip() == "Linger=yes"
